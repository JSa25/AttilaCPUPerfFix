// Build step: compile the flag wave vertex shaders (flagvs.h) once, here, and write them out as bytecode for
// bridgeprobe.c to hand straight to CreateVertexShader. The flag wave ships on by default, so compiling the HLSL
// at start-up would cost every player 264 ms (measured 2026-11-17: 146 + 117 ms, both shaders) whether they have a
// flag pack or not, and would need d3dcompiler_47.dll, which is not there on a stripped Windows or under Proton.
// DXBC is the portable form every driver takes, so the bytes are the same bytes the runtime compile produced.
// usage: fwvs_gen <out header>
#define COBJMACROS
#include <windows.h>
#include <d3dcompiler.h>
#include <stdio.h>
#include "flagvs.h"

int main(int argc, char **argv) {
    if (argc < 2) return fprintf(stderr, "usage: fwvs_gen <out header>\n"), 2;
    HMODULE h = LoadLibraryExA("d3dcompiler_47.dll", NULL, LOAD_LIBRARY_SEARCH_SYSTEM32);
    pD3DCompile comp = h ? (pD3DCompile)(void *)GetProcAddress(h, "D3DCompile") : NULL;
    if (!comp) return fprintf(stderr, "fwvs_gen: no d3dcompiler_47\n"), 1;
    static const char *const entry[2] = {"main_vs", "shadow_vs"};
    ID3DBlob *b[2] = {0};
    for (int k = 0; k < 2; k++) {
        ID3DBlob *err = NULL;
        // the same call install_bridgeprobe used to make at start-up, so the bytes do not change
        if (FAILED(comp(flag_hlsl, sizeof flag_hlsl - 1, "flagvs", NULL, NULL, entry[k], "vs_4_0",
                        D3DCOMPILE_OPTIMIZATION_LEVEL3, 0, &b[k], &err)))
            return fprintf(stderr, "fwvs_gen: %s not compiled: %s\n", entry[k],
                           err ? (const char *)ID3D10Blob_GetBufferPointer(err) : "?"), 1;
    }
    FILE *f = fopen(argv[1], "wb");
    if (!f) return fprintf(stderr, "fwvs_gen: cannot write %s\n", argv[1]), 1;
    fprintf(f, "// Generated by fwvs_gen.c from flagvs.h - do not edit. The flag wave vertex shaders as DXBC.\n");
    for (int k = 0; k < 2; k++) {
        const unsigned char *p = ID3D10Blob_GetBufferPointer(b[k]);
        SIZE_T n = ID3D10Blob_GetBufferSize(b[k]);
        fprintf(f, "static const unsigned char flag_vs_%s[%llu] = {", entry[k], (unsigned long long)n);
        for (SIZE_T i = 0; i < n; i++) fprintf(f, "%s%u,", i % 20 ? "" : "\n    ", p[i]);
        fprintf(f, "\n};\n");
    }
    fprintf(f, "static const unsigned char *const flag_vs_bc[2] = {flag_vs_main_vs, flag_vs_shadow_vs};\n");
    fprintf(f, "static const unsigned flag_vs_bclen[2] = {%llu, %llu};\n",
            (unsigned long long)ID3D10Blob_GetBufferSize(b[0]), (unsigned long long)ID3D10Blob_GetBufferSize(b[1]));
    if (fclose(f)) return fprintf(stderr, "fwvs_gen: write failed\n"), 1;
    printf("fwvs_gen: %s (%lu + %lu bytes of bytecode)\n", argv[1],
           (unsigned long)ID3D10Blob_GetBufferSize(b[0]), (unsigned long)ID3D10Blob_GetBufferSize(b[1]));
    return 0;
}
