# Writes out/gen/: the two files of the 32-bit mod the plugin is built from, with the 64-bit plugin's own version beside
# them (a quoted #include "version.h" finds the file next to the including one first):
#   version.h  = heapfix/version.h (the plugin carries the engine fix's number: both ship in one mod)
#   update.c   = heapfix/update.c, unchanged
#   fgpanel.c  = heapfix/fgpanel.c with its What's new list replaced by src/whatsnew64.inc
# usage: gen_shared64.py <repo root>
import os, sys
root = sys.argv[1]
# the dev tree (heapfix/, x64Review/perffix64/) or the public one (32bit/, shared/, 64bit/); this file is in <tree>/tools
P = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
dev = os.path.isdir(root + '/heapfix')
h32 = root + '/heapfix' if dev else root + '/32bit'      # the 32-bit sources
sh = root + '/heapfix' if dev else root + '/shared'      # the files both sides build (version.h)
src = P + '/src'
gen = P + '/out/gen'
os.makedirs(gen, exist_ok=True)
def put(name, text):
    p = gen + '/' + name
    old = open(p, encoding='utf-8').read() if os.path.exists(p) else None
    if old != text: open(p, 'w', encoding='utf-8', newline='\n').write(text)   # unchanged files keep their time
put('version.h', open(sh + '/version.h', encoding='utf-8').read())   # the engine fix's own number (src/version64.h)
put('update.c', open(h32 + '/update.c', encoding='utf-8').read())
fp = open(h32 + '/fgpanel.c', encoding='utf-8').read()
a = fp.index('static const wchar_t *const WHATS_NEW[] = {')
b = fp.index('};', a) + 2
assert fp.count('static const wchar_t *const WHATS_NEW[] = {') == 1
wn = open(src + '/whatsnew64.inc', encoding='utf-8').read()
wn = wn[wn.index('static const wchar_t *const WHATS_NEW[] = {'):]
put('fgpanel.c', '// GENERATED by gen_shared64.py from heapfix/fgpanel.c (What\'s new: src/whatsnew64.inc) - do not edit\n' + fp[:a] + wn.rstrip() + fp[b:])
