# Writes out/gen/ctxwrap64.c: a wrapper object for the game's immediate D3D11 context (the upscaling add-on, bridge64).
# Every method of ID3D11DeviceContext forwards to the real context through ITS table at the moment of the call, so
# whatever d3d11 puts into the real table is what runs. The wrapper's own table (g_ctxwrap_vtbl) is ours and writable:
# the 32-bit bridge's slot hooks (patch_slot, ctx_slot, mp_hook) go into it unchanged, and d3d11 never swaps them back
# (it does on the real x64 table: Flag Wave's hook was missing at 87 % of Presents, PORTING.md).
# The methods are read from the toolchain's own d3d11.h, so the table matches the header the plugin is built against.
# usage: gen_ctxwrap64.py <d3d11.h> <out.c>
import re, sys
src = open(sys.argv[1], encoding='utf-8').read()
m = re.search(r'typedef struct ID3D11DeviceContextVtbl \{(.*?)\} ID3D11DeviceContextVtbl;', src, re.S)
assert m, 'ID3D11DeviceContextVtbl not found'
meth = re.findall(r'([A-Za-z_][\w \*]*?)\s*\(STDMETHODCALLTYPE \*(\w+)\)\(\s*ID3D11DeviceContext \*This(.*?)\);', m.group(1), re.S)
assert len(meth) > 100, len(meth)
names = [n for _, n, _ in meth]
assert names[:3] == ['QueryInterface', 'AddRef', 'Release'] and len(set(names)) == len(names)

out = ['// GENERATED by tools/gen_ctxwrap64.py from the toolchain\'s d3d11.h - do not edit',
       '// %d methods; the first three (IUnknown) are written by hand below the forwarders.' % len(meth),
       '#define COBJMACROS', '#include <windows.h>', '#include <d3d11.h>', '#include <stdlib.h>',
       'typedef struct { ID3D11DeviceContextVtbl *lpVtbl; ID3D11DeviceContext *real; } CtxWrap;',
       '#define R(This) (((CtxWrap *)(void *)(This))->real)', '']
for ret, name, args in meth[3:]:
    ret = ' '.join(ret.split())
    params = [' '.join(p.split()) for p in args.split(',')[1:]] if args.strip() else []
    pnames = []
    for p in params:
        pm = re.search(r'(\w+)\s*(\[\s*\d*\s*\])?$', p)
        assert pm, (name, p)
        pnames.append(pm.group(1))
    decl = ', '.join(['ID3D11DeviceContext *This'] + params)
    call = ', '.join(['R(This)'] + pnames)
    body = ('return ' if ret != 'void' else '') + 'R(This)->lpVtbl->%s(%s);' % (name, call)
    out.append('static %s STDMETHODCALLTYPE f_%s(%s) { %s }' % (ret, name, decl, body))
out += ['',
        '// the wrapper answers for the interfaces it is (IUnknown, ID3D11DeviceChild, ID3D11DeviceContext); every other one',
        '// (ID3D11DeviceContext1..4, ID3D11Multithread, ...) is the real object\'s, which bypasses the hooks: the loader takes',
        '// ID3D11DeviceContext1 only for ClearView, the bridge ID3D11DeviceContext4 only for its fences',
        'static HRESULT STDMETHODCALLTYPE f_QueryInterface(ID3D11DeviceContext *This, REFIID riid, void **ppv) {',
        '    if (ppv && (IsEqualIID(riid, &IID_IUnknown) || IsEqualIID(riid, &IID_ID3D11DeviceChild) || IsEqualIID(riid, &IID_ID3D11DeviceContext))) {',
        '        R(This)->lpVtbl->AddRef(R(This));',
        '        *ppv = This;',
        '        return S_OK;',
        '    }',
        '    return R(This)->lpVtbl->QueryInterface(R(This), riid, ppv);',
        '}',
        'static ULONG STDMETHODCALLTYPE f_AddRef(ID3D11DeviceContext *This) { return R(This)->lpVtbl->AddRef(R(This)); }',
        '// the wrapper itself is never freed: a call that comes after the last Release reaches a released context, as it would',
        '// without the wrapper (shortcut: a few bytes per device the game makes; it makes one or two)',
        'static ULONG STDMETHODCALLTYPE f_Release(ID3D11DeviceContext *This) { return R(This)->lpVtbl->Release(R(This)); }',
        '',
        'ID3D11DeviceContextVtbl g_ctxwrap_vtbl = {']
out += ['    f_%s,' % n for n in names]
out += ['};', '',
        '// a wrapper around real (which keeps its reference count; the wrapper adds none)',
        'ID3D11DeviceContext *ctxwrap_new(ID3D11DeviceContext *real) {',
        '    CtxWrap *w = calloc(1, sizeof *w);',
        '    if (!w || !real) { free(w); return NULL; }',
        '    w->lpVtbl = &g_ctxwrap_vtbl;',
        '    w->real = real;',
        '    return (ID3D11DeviceContext *)(void *)w;',
        '}',
        '// the real context under a wrapper of ours, else c itself',
        'ID3D11DeviceContext *ctxwrap_real(ID3D11DeviceContext *c) {',
        '    return c && c->lpVtbl == &g_ctxwrap_vtbl ? R(c) : c;',
        '}',
        'unsigned ctxwrap_methods(void) { return %d; }' % len(meth), '']
open(sys.argv[2], 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
print('ctxwrap64: %d methods' % len(meth))
