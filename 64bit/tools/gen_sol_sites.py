# Lists where Sol Invictus's loader changes the game, read from its published source, for the mock-loader test.
# usage: python -I gen_sol_sites.py <sol_repo/attila64/loader> <out header>
# Written: every hook_entry(address, bytes, length, handler) call (a 5-byte jump over the function's first bytes) and
# every row of the g_game_patches byte table. Only addresses, lengths and bytes are taken: facts about what the loader
# does to the game file, no code. Switched-off-by-default and test-only places are included on purpose: the test
# applies all of them at once, the worst case for a plugin sharing the game with the loader.
# Nothing is generated when the folder is missing (the test then uses only its own short list).
import os, re, sys

src, out = sys.argv[1], sys.argv[2]
if not os.path.isdir(src):
    sys.exit(0)

def text(name):
    return open(os.path.join(src, name), encoding='utf-8', errors='replace').read()

version = '?'
m = re.search(r'APP_VERSION_TEXT\s+"([^"]+)"', text('version.h')) if os.path.isfile(os.path.join(src, 'version.h')) else None
if m: version = m.group(1)

hooks = {}
HOOK = re.compile(r'hook_entry\(\s*0x([0-9a-fA-F]+)\s*,\s*[A-Za-z_0-9]+\s*,\s*(\d+)\s*,')
for name in sorted(os.listdir(src)):
    if not name.endswith(('.inc', '.c')): continue
    for line in text(name).split('\n'):
        code = line.split('//')[0]
        for h in HOOK.finditer(code):
            hooks[int(h.group(1), 16)] = (int(h.group(2)), name)

rows = []
ROW = re.compile(r'\{\s*"[^"]*"\s*,\s*0x([0-9a-fA-F]+)\s*,\s*\{([^}]*)\}\s*,\s*\{([^}]*)\}\s*,\s*(\d+)\s*\}', re.S)
body = re.search(r'g_game_patches\[\]\s*=\s*\{(.*?)\n\};', text('game_fixes.inc'), re.S)
if body:
    clean = re.sub(r'//[^\n]*', '', body.group(1))
    for r in ROW.finditer(clean):
        n = int(r.group(4))
        old = [int(x, 0) for x in r.group(2).replace('\n', ' ').split(',') if x.strip()]
        new = [int(x, 0) for x in r.group(3).replace('\n', ' ').split(',') if x.strip()]
        old += [0] * (n - len(old)); new += [0] * (n - len(new))
        rows.append((int(r.group(1), 16), n, old[:n], new[:n]))

with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// GENERATED by tools/gen_sol_sites.py from the published loader source - do not edit\n')
    f.write('#define SOL_GEN_VERSION "%s"\n' % version)
    f.write('static const struct { uint32_t at; uint8_t len; const char *file; } SOL_GEN_HOOKS[] = {\n')
    for at in sorted(hooks):
        f.write('    {0x%x, %d, "%s"},\n' % (at, hooks[at][0], hooks[at][1]))
    f.write('};\nstatic const struct { uint32_t at; uint8_t len; uint8_t old[8], now[8]; } SOL_GEN_BYTES[] = {\n')
    for at, n, old, new in rows:
        f.write('    {0x%x, %d, {%s}, {%s}},\n' % (at, n, ', '.join('0x%02x' % b for b in old), ', '.join('0x%02x' % b for b in new)))
    f.write('};\n')
print('loader %s: %d hooked function starts, %d byte patches' % (version, len(hooks), len(rows)))
